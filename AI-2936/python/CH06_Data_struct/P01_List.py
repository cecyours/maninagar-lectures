# Creating
numbers = [10, 20, 30, 40, 50]
print(numbers)

data = [25, "Python", 3.14, True]
print(data)

items = []
print(items)

# Accessing Elements
fruits = ["Apple", "Banana", "Mango", "Orange"]
print(fruits[0])
print(fruits[2])

# Negative Indexing
numbers = [10, 20, 30, 40]
print(numbers[-1])
print(numbers[-2])

# Changing 
colors = ["Red", "Blue", "Green"]
colors[1] = "Yellow"
print(colors)

# append()
numbers = [1, 2, 3]
numbers.append(4)
print(numbers)

# insert()
numbers = [10, 20, 30]
numbers.insert(1, 15)
print(numbers)

# remove()
fruits = ["Apple", "Banana", "Mango"]
fruits.remove("Banana")
print(fruits)

# pop()
numbers = [5, 10, 15, 20]
numbers.pop(2)
print(numbers)

# Managing a List of Students
students = ["Amit", "Doe", "Mary"]
print("Original List:", students)
students.append("Neha")
students[1] = "Rohan"
print("Updated List:", students)
