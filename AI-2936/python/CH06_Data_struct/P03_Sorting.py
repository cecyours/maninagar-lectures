# sort()
numbers = [50, 20, 40, 10, 30]
numbers.sort()
print("Sorted list:", numbers)

# Descending Order
numbers = [50, 20, 40, 10, 30]
numbers.sort(reverse=True)
print("Descending order:", numbers)

# sorted()
numbers = [8, 3, 6, 1, 9]
sorted_list = sorted(numbers)
print("Original list:", numbers)
print("Sorted list:", sorted_list)