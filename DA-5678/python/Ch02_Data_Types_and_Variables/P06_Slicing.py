
# String Slicing
text = "PythonProgramming"
# Extract "Python"
print(text[0:6])
# Extract "Programming"
print(text[6:])

text = "PythonProgramming"
# Last character
print(text[-1])
# Last 11 characters
print(text[-11:])

text = "PythonProgramming"
# Every 2nd character
print(text[0:6:2])
# Reverse the string
print(text[::-1])
