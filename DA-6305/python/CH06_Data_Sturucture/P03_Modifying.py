colors = ["Red", "Blue", "Green"]
colors[1] = "Yellow"
print(colors)

# append()
numbers = [1, 2, 3]
numbers.append(4)
print(numbers)

# insert()
numbers = [10, 20, 30]
numbers.insert(1, 15)
print(numbers)

# remove()
fruits = ["Apple", "Banana", "Mango"]
fruits.remove("Banana")
print(fruits)

# pop()
numbers = [5, 10, 15, 20]
numbers.pop(2)
print(numbers)

#  List of Students
students = ["Amit", "Doe", "Mary"]
print("Original List:", students)
students.append("Neha")
students[1] = "Rohan"
print("Updated List:", students)
